import { mkdirSync, existsSync, realpathSync, symlinkSync } from 'node:fs';
import { createRequire } from 'node:module';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';
const audit = spawnSync(process.execPath, [fileURLToPath(new URL('./check-licenses.mjs', import.meta.url)), ...process.argv.slice(2)], { stdio: 'inherit' });
if (audit.status !== 0) process.exit(audit.status ?? 1);
const tools = process.env.BETA_TOOLS_DIR;
if (!tools) throw new Error('Set BETA_TOOLS_DIR to the directory containing desktop/node_modules/@tauri-apps/cli.');
const require = createRequire(import.meta.url);
const cli = require.resolve('@tauri-apps/cli/tauri.js', { paths: [resolve(tools, 'desktop')] });
if (!process.env.CARGO_TARGET_DIR) throw new Error('Set CARGO_TARGET_DIR to external build output.');
const cache = resolve(tools, 'tauri-bundler');
const junction = resolve(process.env.CARGO_TARGET_DIR, '.tauri');
mkdirSync(cache, { recursive: true });
mkdirSync(process.env.CARGO_TARGET_DIR, { recursive: true });
if (!existsSync(junction)) symlinkSync(cache, junction, 'junction');
else if (realpathSync(junction).toLowerCase() !== realpathSync(cache).toLowerCase()) throw new Error('Cargo .tauri cache must point to BETA_TOOLS_DIR/tauri-bundler.');
const result = spawnSync(process.execPath, [cli, ...process.argv.slice(2)], { stdio: 'inherit', env: process.env });
process.exit(result.status ?? 1);
